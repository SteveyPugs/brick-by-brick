import XCTest

final class BuildsUITests: XCTestCase {
    @MainActor
    private func replace(_ field: XCUIElement, with text: String) {
        field.tap()
        let old = field.value as? String ?? ""
        field.typeText(String(repeating: XCUIKeyboardKey.delete.rawValue, count: old.count) + text)
    }

    @MainActor
    func testMeasuredBricksEditingAndDemoPlan() throws {
        continueAfterFailure = false
        let app = XCUIApplication()
        app.launch()
        XCTAssertTrue(app.buttons["add-build"].waitForExistence(timeout: 10))
        app.buttons["add-build"].tap()
        app.descendants(matching: .any).matching(identifier: "build-name").firstMatch.typeText("Measured goal")
        app.buttons["save-build"].tap()
        app.staticTexts["Measured goal"].tap()
        app.buttons["edit-build"].tap()
        replace(app.textFields["edit-name"], with: "My measured goal")
        app.buttons["save-name"].tap()
        XCTAssertTrue(app.staticTexts["My measured goal"].exists)
        app.buttons["add-wall"].tap()
        app.textFields["wall-name"].typeText("Activity")
        app.buttons["save-wall"].tap()
        app.staticTexts["Activity"].tap()
        app.buttons["edit-wall"].tap()
        replace(app.textFields["edit-name"], with: "My activity")
        app.buttons["save-name"].tap()
        XCTAssertTrue(app.staticTexts["My activity"].exists)
        app.buttons["add-brick"].tap()
        app.textFields["brick-name"].typeText("Drink water")
        app.buttons["Track progress"].tap()
        replace(app.textFields["brick-target"], with: "8")
        app.textFields["brick-unit"].tap()
        app.textFields["brick-unit"].typeText("cups")
        app.buttons["save-brick"].tap()
        app.buttons["Drink water"].tap()
        replace(app.textFields["progress-value"], with: "1.5")
        XCTAssertTrue(app.buttons["save-progress"].isEnabled)
        replace(app.textFields["progress-value"], with: "5")
        app.buttons["save-progress"].tap()
        XCTAssertEqual(app.buttons["Drink water"].value as? String, "5 of 8 cups")
        app.buttons["Options for Drink water"].tap()
        app.buttons["Rename"].tap()
        replace(app.textFields["edit-name"], with: "Water break")
        app.buttons["save-name"].tap()
        XCTAssertEqual(app.buttons["Water break"].value as? String, "5 of 8 cups")
        app.buttons["Water break"].tap()
        replace(app.textFields["progress-value"], with: "8")
        app.buttons["save-progress"].tap()
        XCTAssertTrue(app.staticTexts["1 of 1 complete"].exists)
        app.buttons["add-brick"].tap()
        app.textFields["brick-name"].typeText("Walk")
        app.buttons["Track progress"].tap()
        replace(app.textFields["brick-target"], with: "2.5")
        app.buttons["brick-unit-miles"].tap()
        app.buttons["save-brick"].tap()
        app.buttons["Walk"].tap()
        replace(app.textFields["progress-value"], with: "1.25")
        app.buttons["save-progress"].tap()
        app.terminate(); app.launch()
        XCTAssertTrue(app.staticTexts["My measured goal"].waitForExistence(timeout: 10))
        app.staticTexts["My measured goal"].tap()
        app.staticTexts["My activity"].tap()
        XCTAssertEqual(app.buttons["Water break"].value as? String, "8 of 8 cups")
        XCTAssertEqual(app.buttons["Walk"].value as? String, "1.25 of 2.5 miles")
        app.terminate(); app.launch()
        app.buttons["open-planner"].tap()
        XCTAssertTrue(app.staticTexts["Build a plan you can start"].exists)
        app.descendants(matching: .any).matching(identifier: "planner-goal").firstMatch.tap()
        app.descendants(matching: .any).matching(identifier: "planner-goal").firstMatch.typeText("Read more books")
        app.buttons["planner-continue"].tap()
        app.buttons["planner-starter"].tap()
        app.buttons["Cancel"].tap()
        XCTAssertFalse(app.staticTexts["Read more books"].exists)
        app.buttons["open-planner"].tap()
        app.descendants(matching: .any).matching(identifier: "planner-goal").firstMatch.tap()
        app.descendants(matching: .any).matching(identifier: "planner-goal").firstMatch.typeText("Read more books")
        app.buttons["planner-continue"].tap()
        let details = app.descendants(matching: .any).matching(identifier: "planner-follow-up").firstMatch
        details.tap()
        details.typeText("10 minutes every day")
        app.buttons["planner-starter"].tap()
        XCTAssertTrue(app.staticTexts["Starter draft — no AI"].exists)
        replace(app.textFields["plan-title"], with: "My reading plan")
        app.staticTexts["Choose a book"].tap()
        replace(app.textFields["plan-brick-name"], with: "Pick my next book")
        app.navigationBars["Edit suggestion"].buttons.element(boundBy: 0).tap()
        app.buttons["save-plan"].tap()
        XCTAssertTrue(app.staticTexts["My reading plan"].waitForExistence(timeout: 5))
        app.staticTexts["My reading plan"].tap()
        app.staticTexts["Make space for reading"].tap()
        XCTAssertTrue(app.buttons["Pick my next book"].exists)
        app.navigationBars["Your Wall"].buttons.element(boundBy: 0).tap()
        app.staticTexts["Build a reading routine"].tap()
        XCTAssertEqual(app.buttons["Read your book"].value as? String, "0 of 10 minutes")
        app.buttons["Read your book"].tap()
        replace(app.textFields["progress-value"], with: "10")
        app.buttons["save-progress"].tap()
        XCTAssertEqual(app.buttons["Read your book"].value as? String, "10 of 10 minutes")
    }

    @MainActor
    func testCreateValidateCancelAndRelaunch() throws {
        continueAfterFailure = false
        let app = XCUIApplication()
        app.launch()
        XCTAssertTrue(app.buttons["add-build"].waitForExistence(timeout: 10))
        app.buttons["add-build"].tap()
        let save = app.buttons["save-build"]
        XCTAssertTrue(save.waitForExistence(timeout: 5))
        XCTAssertFalse(save.isEnabled)
        let name = app.descendants(matching: .any).matching(identifier: "build-name").firstMatch
        name.tap()
        name.typeText("   ")
        XCTAssertFalse(save.isEnabled)
        app.buttons["Cancel"].tap()
        XCTAssertFalse(save.exists)

        app.buttons["add-build"].tap()
        let title = "Build a reading habit"
        name.tap()
        name.typeText(title)
        let why = app.descendants(matching: .any).matching(identifier: "build-motivation").firstMatch
        why.tap()
        why.typeText("Make time to learn something new.")
        XCTAssertTrue(save.isEnabled)
        save.tap()
        XCTAssertTrue(app.staticTexts[title].waitForExistence(timeout: 5))

        app.terminate()
        app.launch()
        XCTAssertTrue(app.staticTexts[title].waitForExistence(timeout: 10))
        XCTAssertTrue(app.staticTexts["Make time to learn something new."].exists)
        let screenshot = XCTAttachment(screenshot: app.screenshot())
        screenshot.name = "Saved Builds after relaunch"
        screenshot.lifetime = .keepAlways
        add(screenshot)
        app.staticTexts[title].tap()
        XCTAssertTrue(app.navigationBars["Your Build"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.staticTexts[title].exists)
        app.buttons["add-wall"].tap()
        let saveWall = app.buttons["save-wall"]
        XCTAssertTrue(saveWall.waitForExistence(timeout: 5))
        XCTAssertFalse(saveWall.isEnabled)
        let wallName = app.textFields["wall-name"]
        wallName.tap()
        wallName.typeText("   ")
        XCTAssertFalse(saveWall.isEnabled)
        app.buttons["Cancel"].tap()
        app.buttons["add-wall"].tap()
        wallName.tap()
        wallName.typeText(String(repeating: "a", count: 81))
        XCTAssertFalse(saveWall.isEnabled)
        app.buttons["Cancel"].tap()
        app.buttons["add-wall"].tap()
        wallName.tap()
        wallName.typeText("  Read every evening  ")
        XCTAssertTrue(saveWall.isEnabled)
        saveWall.tap()
        XCTAssertTrue(app.staticTexts["Read every evening"].waitForExistence(timeout: 5))
        app.buttons["add-wall"].tap()
        wallName.tap()
        wallName.typeText("Visit the library")
        saveWall.tap()
        XCTAssertTrue(app.staticTexts["Visit the library"].waitForExistence(timeout: 5))
        app.terminate()
        app.launch()
        XCTAssertTrue(app.staticTexts[title].waitForExistence(timeout: 10))
        XCTAssertTrue(app.staticTexts["2 Walls"].exists)
        app.staticTexts[title].tap()
        XCTAssertTrue(app.staticTexts["Read every evening"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.staticTexts["Visit the library"].exists)
        app.staticTexts["Read every evening"].tap()
        XCTAssertTrue(app.navigationBars["Your Wall"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.staticTexts["Read every evening"].exists)
        app.buttons["add-brick"].tap()
        let saveBrick = app.buttons["save-brick"]
        XCTAssertTrue(saveBrick.waitForExistence(timeout: 5))
        XCTAssertFalse(saveBrick.isEnabled)
        app.textFields["brick-name"].typeText("   ")
        XCTAssertFalse(saveBrick.isEnabled)
        app.buttons["Cancel"].tap()
        app.buttons["add-brick"].tap()
        app.textFields["brick-name"].typeText("  Read 10 minutes  ")
        saveBrick.tap()
        let brick = app.buttons["Read 10 minutes"]
        XCTAssertTrue(brick.waitForExistence(timeout: 5))
        XCTAssertEqual(brick.value as? String, "Incomplete")
        brick.tap()
        XCTAssertEqual(brick.value as? String, "Complete")
        XCTAssertTrue(app.staticTexts["1 of 1 complete"].exists)
        app.terminate()
        app.launch()
        app.staticTexts[title].tap()
        app.staticTexts["Read every evening"].tap()
        XCTAssertTrue(brick.waitForExistence(timeout: 5))
        XCTAssertEqual(brick.value as? String, "Complete")
        brick.tap()
        XCTAssertEqual(brick.value as? String, "Incomplete")

        app.buttons["Options for Read 10 minutes"].tap()
        app.buttons["Delete"].tap()
        XCTAssertTrue(app.alerts["Delete this Brick?"].waitForExistence(timeout: 5))
        app.alerts.buttons["Cancel"].tap()
        XCTAssertTrue(brick.exists)
        app.buttons["Options for Read 10 minutes"].tap()
        app.buttons["Delete"].tap()
        app.alerts.buttons["Delete Brick"].tap()
        XCTAssertFalse(brick.exists)
        // Leave a child in the Wall to exercise cascading deletion.
        app.buttons["add-brick"].tap()
        let temporaryName = app.textFields["brick-name"]
        XCTAssertTrue(temporaryName.waitForExistence(timeout: 5))
        temporaryName.tap()
        temporaryName.typeText("Temporary action")
        XCTAssertEqual(temporaryName.value as? String, "Temporary action")
        saveBrick.tap()
        let temporaryBrick = app.buttons["Temporary action"]
        XCTAssertTrue(temporaryBrick.waitForExistence(timeout: 5))
        app.buttons["delete-wall"].tap()
        XCTAssertTrue(app.alerts["Delete this Wall?"].waitForExistence(timeout: 5))
        app.alerts.buttons["Cancel"].tap()
        XCTAssertTrue(temporaryBrick.waitForExistence(timeout: 5))
        app.buttons["delete-wall"].tap()
        app.alerts.buttons["Delete Wall"].tap()
        XCTAssertTrue(app.navigationBars["Your Build"].waitForExistence(timeout: 5))
        XCTAssertFalse(app.staticTexts["Read every evening"].exists)
        XCTAssertTrue(app.staticTexts["Visit the library"].exists)
        app.terminate()
        app.launch()
        app.staticTexts[title].tap()
        XCTAssertFalse(app.staticTexts["Read every evening"].exists)
        XCTAssertTrue(app.staticTexts["Visit the library"].exists)
        app.buttons["delete-build"].tap()
        XCTAssertTrue(app.alerts["Delete this Build?"].waitForExistence(timeout: 5))
        app.alerts.buttons["Cancel"].tap()
        XCTAssertTrue(app.staticTexts[title].exists)
        app.buttons["delete-build"].tap()
        app.alerts.buttons["Delete Build"].tap()
        XCTAssertTrue(app.buttons["create-first-build"].waitForExistence(timeout: 5))
        app.terminate()
        app.launch()
        XCTAssertTrue(app.buttons["create-first-build"].waitForExistence(timeout: 10))
        XCTAssertFalse(app.staticTexts[title].exists)
    }
}
